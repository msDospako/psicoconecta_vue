import { createHash, randomBytes, timingSafeEqual } from 'node:crypto'
import pg from 'pg'
import { services } from '../../src/data/services.js'
import { demoUsers } from '../../src/data/users.js'

let pool
let ready
const digest = (value) => createHash('sha256').update(value).digest()
const tokenHash = (value) => digest(value).toString('hex')
const unpack = ({ id, content }) => ({ id, ...content })
const missing = () => send(404, { error: 'Servicio no encontrado.' })
const unauthorized = () => send(401, { error: 'Inicia sesión para administrar el catálogo.' })

async function migrate() {
  const client = await pool.connect()
  try {
    await client.query('BEGIN')
    await client.query('SELECT pg_advisory_xact_lock(45137891)')
    await client.query(`
      CREATE TABLE IF NOT EXISTS psicoconecta_migrations (version INTEGER PRIMARY KEY);
      CREATE TABLE IF NOT EXISTS psicoconecta_services (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, content JSONB NOT NULL);
      CREATE TABLE IF NOT EXISTS psicoconecta_sessions (token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL, expires_at TIMESTAMPTZ NOT NULL);
    `)
    const migration = await client.query('INSERT INTO psicoconecta_migrations VALUES (1) ON CONFLICT DO NOTHING RETURNING version')
    if (migration.rowCount) {
      for (const { id, ...content } of services) {
        await client.query('INSERT INTO psicoconecta_services (id, content) VALUES ($1, $2)', [id, content])
      }
      await client.query(`SELECT setval(pg_get_serial_sequence('psicoconecta_services', 'id'), (SELECT MAX(id) FROM psicoconecta_services))`)
    }
    await client.query('COMMIT')
  } catch (error) {
    await client.query('ROLLBACK')
    throw error
  } finally {
    client.release()
  }
}

async function database() {
  const connectionString = process.env.DATABASE_URL || process.env.NETLIFY_DB_URL
  if (!connectionString) throw new Error('Falta DATABASE_URL en el entorno de la función.')
  pool ??= new pg.Pool({ connectionString, max: 2, connectionTimeoutMillis: 5000 })
  ready ??= migrate().catch((error) => {
    ready = undefined
    throw error
  })
  await ready
  return pool
}

function send(status, body) {
  const headers = { 'Cache-Control': 'no-store' }
  return body === undefined ? new Response(null, { status, headers }) : Response.json(body, { status, headers })
}

async function readJson(request) {
  try {
    const raw = await request.text()
    return raw.length <= 16000 ? JSON.parse(raw) : null
  } catch {
    return null
  }
}

function validateService(input) {
  if (!input || typeof input !== 'object') return null
  const limits = { title: 120, category: 60, emoji: 32, description: 2000 }
  const service = {}
  for (const [field, limit] of Object.entries(limits)) {
    const value = typeof input[field] === 'string' ? input[field].trim() : ''
    if (!value || value.length > limit) return null
    service[field] = value
  }
  const { price, rating, includes } = input
  if (!Number.isInteger(price) || price < 0 || price > 1000000 ||
      !Number.isInteger(rating) || rating < 1 || rating > 5 ||
      !Array.isArray(includes) || !includes.length || includes.length > 15 ||
      includes.some((item) => typeof item !== 'string' || !item.trim() || item.trim().length > 160)) return null
  return { ...service, price, rating, includes: includes.map((item) => item.trim()) }
}

export default async function handler(request) {
  try {
    const path = new URL(request.url).pathname.replace(/^\/\.netlify\/functions\/api(?=\/)/, '/api')
    const { method } = request
    const token = request.headers.get('authorization')?.match(/^Bearer ([a-f0-9]{64})$/)?.[1]
    const hash = token ? tokenHash(token) : null

    if (path === '/api/session' && method === 'POST') {
      const input = await readJson(request)
      const index = demoUsers.findIndex((account) => account.email === String(input?.email ?? '').trim().toLowerCase())
      const password = [process.env.ADVISOR_PASSWORD, process.env.ADMIN_PASSWORD][index]
      if (!password || typeof input?.password !== 'string' || !timingSafeEqual(digest(password), digest(input.password))) {
        return send(401, { error: 'El correo o la contraseña no coinciden.' })
      }
      const db = await database()
      const account = demoUsers[index]
      const sessionToken = randomBytes(32).toString('hex')
      await db.query('DELETE FROM psicoconecta_sessions WHERE expires_at <= NOW()')
      await db.query("INSERT INTO psicoconecta_sessions VALUES ($1, $2, NOW() + INTERVAL '8 hours')", [tokenHash(sessionToken), account.id])
      return send(200, { user: account, token: sessionToken })
    }

    if (path === '/api/session' && method === 'DELETE') {
      if (hash) await (await database()).query('DELETE FROM psicoconecta_sessions WHERE token_hash = $1', [hash])
      return send(204)
    }

    if (path === '/api/session' || method !== 'GET') {
      if (!hash) return unauthorized()
      const db = await database()
      const session = await db.query('SELECT user_id FROM psicoconecta_sessions WHERE token_hash = $1 AND expires_at > NOW()', [hash])
      const user = demoUsers.find((account) => account.id === session.rows[0]?.user_id)
      if (!user) return unauthorized()
      if (path === '/api/session') return send(200, user)
    }

    const match = path.match(/^\/api\/servicios(?:\/([1-9]\d*))?$/)
    if (!match) return missing()
    const id = match[1] ? Number(match[1]) : null
    if (id > 2147483647) return missing()
    const db = await database()
    if (method === 'GET' && id === null) {
      const result = await db.query('SELECT id, content FROM psicoconecta_services ORDER BY id')
      return send(200, result.rows.map(unpack))
    }
    if (method === 'GET') {
      const result = await db.query('SELECT id, content FROM psicoconecta_services WHERE id = $1', [id])
      return result.rowCount ? send(200, unpack(result.rows[0])) : missing()
    }
    if ((method === 'POST' && id === null) || (method === 'PUT' && id !== null)) {
      const content = validateService(await readJson(request))
      if (!content) return send(400, { error: 'Revisa los campos del servicio. Incluye de 1 a 15 elementos de hasta 160 caracteres cada uno.' })
      if (method === 'POST') {
        const result = await db.query('INSERT INTO psicoconecta_services (content) VALUES ($1) RETURNING id, content', [content])
        return send(201, unpack(result.rows[0]))
      }
      const result = await db.query('UPDATE psicoconecta_services SET content = $1 WHERE id = $2 RETURNING id, content', [content, id])
      return result.rowCount ? send(200, unpack(result.rows[0])) : missing()
    }
    if (method === 'DELETE' && id !== null) {
      const result = await db.query('DELETE FROM psicoconecta_services WHERE id = $1', [id])
      return result.rowCount ? send(204) : missing()
    }
    return send(405, { error: 'Operación no disponible.' })
  } catch (error) {
    console.error('Error en el catálogo:', error.code || error.name)
    return send(500, { error: 'No se pudo completar la operación.' })
  }
}
